const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs/promises');
const path = require('node:path');
process.chdir(path.resolve(__dirname, '..'));
process.env.SMTP_HOST = '';
const { prisma } = require('../dist/config/database');
const { sha256, signAccessToken } = require('../dist/utils/security');
const service = require('../dist/services/announcements.service');
const mail = require('../dist/services/mail.service');
const originalRecipients = service.recipientWhere;
const users = [];
