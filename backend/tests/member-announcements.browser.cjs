const { processAnnouncementJobs } = require('../dist/services/announcement-jobs.service');
const site = process.env.ANNOUNCEMENTS_WEB_URL || 'http://127.0.0.1:5177';
const base = process.env.ANNOUNCEMENTS_API_URL || 'http://127.0.0.1:5005/api/v1';
const output = '/private/tmp/member-announcements-browser';
const prefix = `member-ann-${crypto.randomUUID().slice(0, 8)}`;
let browser, memberPage, editor;
const errors = [];
async function actor(role) {
  const user = await prisma.user.create({ data: { role, status: 'ACTIVE', fullName: `Announcement Test ${role}`, email: `${prefix}-${role}@example.test`, ...(role === 'MEMBER' ? { memberProfile: { create: { professionalType: 'Academic Researcher', institution: 'Test Institute', country: 'India' } } } : {}) } });
  users.push(user);
  const session = await prisma.session.create({ data: { userId: user.id, tokenHash: sha256(crypto.randomUUID()), expiresAt: new Date(Date.now() + 3600000) } });
  return { ...user, token: signAccessToken({ sub: user.id, role, sessionId: session.id }) };
}
async function screenshot(page, name) {
  await page.screenshot({ path: path.join(output, `${name}.png`), fullPage: !(await page.getByRole('dialog').count()) });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name}: page overflow`);
  for (const dialog of await page.getByRole('dialog').all()) assert.ok(await dialog.evaluate(n => n.scrollWidth <= n.clientWidth), `${name}: dialog overflow`);
}
